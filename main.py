# Запрашиваем рост пользователя до тех пор,
# пока не введён требуемый рост 1.8 метра

while True:
    height = float(input("Введите ваш рост в метрах: "))

    if height == 1.8:
        print("Рост соответствует заданному значению.")
        break
    else:
        print(f"Введённый рост {height:.2f} м отличается от нужного. Попробуйте ещё раз.")